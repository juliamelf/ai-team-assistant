"""Добавляет в матрицу знания и навыки по мобильному тестированию (листы «Ручное» и «Автоматизированное»).

Запуск:  python3 add_mobile.py исходный.xlsx результат.xlsx
Пишет только в пустые ячейки нужного уровня; строки не вставляет, формулы и оформление не трогает.
"""
import sys

from openpyxl import load_workbook
from openpyxl.cell.cell import MergedCell

P = "Для мобильных продуктов: "

ADDITIONS = {
    "Ручное": {
        "C11": P + "знание особенностей платформ iOS и Android: версии ОС, типы устройств, способы установки сборок (A/03.4)",
        "D11": P + "умение устанавливать сборку на устройство или эмулятор и проходить на них тест-кейсы (A/03.4)",
        "E20": P + "знание специфики мобильных приложений: жизненный цикл приложения, разрешения, прерывания, работа при плохой сети (B/01.5)",
        "F19": P + "опыт тестирования мобильных приложений на iOS и Android: жесты, ориентация экрана, прерывания, обновление версии (A/03.4)",
        "G18": P + "знание типов мобильных приложений (нативные, гибридные, веб) и их влияния на тестирование (B/03.5)",
        "H19": P + "умение снимать логи и трафик с устройства (Android Studio, Xcode, снифферы) для локализации багов (B/03.5)",
        "J25": P + "умение подбирать набор устройств и версий ОС для регресса по данным о пользователях (C/02.6)",
        "J26": P + "опыт организации тестирования на ферме устройств или в облачном сервисе и проверок перед публикацией в магазинах приложений (C/03.6)",
    },
    "Автоматизированное": {
        "E18": P + "знание инструментов мобильной автоматизации (Appium, Espresso, XCUITest или аналоги) (B/01.5)",
        "F15": P + "умение писать автотесты для мобильных приложений по тест-кейсам (B/01.5)",
        "H15": P + "опыт запуска мобильных автотестов на эмуляторах и ферме устройств в CI/CD (B/02.5)",
        "J14": P + "опыт проектирования автоматизации для iOS и Android с общим кодом тестов (B/01.5)",
    },
}
# строки с фиксированной высотой 15,75, в которые добавлен текст: снимаем фиксацию, как у строк блоков A и B
AUTO_HEIGHT_ROWS = {"Ручное": [25, 26]}

NOTE_MARK = "Пометка «доп.»"
NOTE_ADD = " Строки, которые начинаются словами «Для мобильных продуктов», нужны только командам с мобильным приложением."


def main(src, dst):
    wb = load_workbook(src)
    for sheet, cells in ADDITIONS.items():
        ws = wb[sheet]
        for coord, text in cells.items():
            cell = ws[coord]
            if isinstance(cell, MergedCell) or cell.value not in (None, ""):
                raise SystemExit(f"{sheet}!{coord} занята: {getattr(cell, 'value', 'объединённая ячейка')!r}")
            cell.value = text
        for r in AUTO_HEIGHT_ROWS.get(sheet, []):
            ws.row_dimensions[r].height = None
    ws = wb["Инструкция"]
    hits = [c for row in ws.iter_rows() for c in row if isinstance(c.value, str) and c.value.startswith(NOTE_MARK)]
    if len(hits) != 1:
        raise SystemExit("Не найдена строка инструкции про пометку «доп.»")
    if NOTE_ADD.strip() not in hits[0].value:
        hits[0].value = hits[0].value.rstrip() + NOTE_ADD
    wb.save(dst)
    print("добавлено строк:", sum(len(v) for v in ADDITIONS.values()))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
